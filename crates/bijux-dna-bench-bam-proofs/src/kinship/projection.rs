use super::models::BamKinshipCompleteRow;
use super::observations::LocalKinshipPairwiseResult;
use super::observations::LocalKinshipSmokeCaseReport;
use super::paths::path_relative_to_repo;
use crate::downstream::observations::ParserObservation;
